"""Kiểm thử headless trang Điều chỉnh giá HĐ (desktop 1440 + mobile 390). Dùng: python dieu_chinh/test_ui.py [base_url]"""
import sys, os
from playwright.sync_api import sync_playwright
B = (sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8765/").rstrip("/") + "/"
S = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "screenshots"); os.makedirs(S, exist_ok=True)
R, errs = [], []
def ok(n, c, info=""): R.append((n, bool(c))); print(("PASS " if c else "FAIL ") + n, info)
with sync_playwright() as p:
    b = p.chromium.launch()
    for mode, vp in (("desktop", dict(width=1440, height=900)), ("mobile", dict(width=390, height=844))):
        ctx = b.new_context(viewport=vp, is_mobile=mode == "mobile", has_touch=mode == "mobile", accept_downloads=True)
        pg = ctx.new_page()
        pg.on("pageerror", lambda e, m=mode: errs.append(f"{m}: {e}")); pg.on("console", lambda x, m=mode: x.type == "error" and errs.append(f"{m} console: {x.text}"))
        sh = lambda n, full=True: pg.screenshot(path=f"{S}/dieuchinh_{mode}_{n}.png", full_page=full)
        pg.goto(B + "dieu-chinh.html", wait_until="domcontentloaded"); pg.wait_for_selector("#tbl tr.r"); pg.wait_for_timeout(500)
        ok(f"{mode} kpis", pg.locator("#kpi .hk").count() == 4)
        nb = pg.locator("#tbl tr.r").count(); ok(f"{mode} rows Bắc", nb == 27, nb)
        ok(f"{mode} groups", pg.locator("#tbl tr.g").count() == 5, pg.locator("#tbl tr.g").count())
        ok(f"{mode} badges", pg.locator("#tbl .bd").count() >= 27)
        ok(f"{mode} nav link", pg.locator(".hn-links a.hot").count() == 1)
        ok(f"{mode} no h-overflow", pg.evaluate("document.documentElement.scrollWidth <= innerWidth + 1"), pg.evaluate("[document.documentElement.scrollWidth, innerWidth]"))
        sh("01_bac")
        pg.click("#rg button[data-k=nam]"); pg.wait_for_timeout(200); nn = pg.locator("#tbl tr.r").count(); ok(f"{mode} rows Nam", nn == 29, nn); sh("02_nam")
        pg.click("#sf button[data-k=down]"); pg.wait_for_timeout(150); nd = pg.locator("#tbl tr.r").count(); ok(f"{mode} filter down", 0 < nd < nn, nd)
        ok(f"{mode} filter consistency", pg.locator("#tbl tr.r").filter(has=pg.locator(".bd.down")).count() == nd)
        pg.click("#sf button[data-k='']"); pg.fill("#q", "be tong m400"); pg.wait_for_timeout(150); ok(f"{mode} search", pg.locator("#tbl tr.r").count() == 1, pg.locator("#tbl tr.r").count()); pg.fill("#q", ""); pg.wait_for_timeout(100)
        pg.check("#onlyw"); pg.wait_for_timeout(100); ok(f"{mode} only weighted", pg.locator("#tbl tr.r").count() == 10, pg.locator("#tbl tr.r").count()); pg.uncheck("#onlyw")
        pg.click("#rg button[data-k=cmp]"); pg.wait_for_timeout(200); ok(f"{mode} compare", pg.locator("#tbl tr.r").count() >= 29, pg.locator("#tbl tr.r").count()); sh("03_compare")
        pg.click("#rg button[data-k=bac]"); pg.wait_for_timeout(150)
        pg.locator("#tbl tr.r[data-k='bac|M400']").click(); pg.wait_for_selector("#dlg[open] canvas"); pg.wait_for_timeout(500)
        ok(f"{mode} dialog sources", pg.locator("#dlg-b table").first.locator("tbody tr").count() >= 2)
        sh("04_detail_daily", False)
        pg.click("#cg button[data-k=m]"); pg.wait_for_timeout(400); sh("05_detail_monthly_forecast", False)
        ok(f"{mode} forecast rows in dialog", pg.locator("#dlg-b table").nth(1).locator("tbody tr").count() == 3)
        pg.click("#dlg-x"); pg.wait_for_timeout(150); ok(f"{mode} dialog closed", not pg.locator("#dlg[open]").count())
        pg.locator("#tbl tr.r[data-k='bac|CATTO']").click(); pg.wait_for_selector("#dlg[open]"); ok(f"{mode} missing item dialog no chart", pg.locator("#dlg canvas").count() == 0); pg.keyboard.press("Escape"); pg.wait_for_timeout(150)
        ok(f"{mode} forecast ranking", pg.locator("#fct tbody tr").count() >= 20, pg.locator("#fct tbody tr").count())
        pg.click("#fh button[data-k='12']"); pg.click("#fb button[data-k=ntc]"); pg.wait_for_timeout(150); ok(f"{mode} fc toggles", pg.locator("#fct tbody tr").count() >= 15)
        pg.locator("#fct").scroll_into_view_if_needed(); sh("06_forecast", False)
        if mode == "desktop":
            with pg.expect_download() as d: pg.click("#bcsv")
            path = d.value.path(); txt = open(path, encoding="utf-8-sig").read(); ok("csv export", txt.startswith("Miền,Nhóm,Mã") and txt.count("\n") >= 27, txt.count("\n"))
            r = pg.request.get(B + "dieu-chinh.xlsx"); ok("xlsx served", r.status == 200 and r.body()[:2] == b"PK", r.status)
            pg.emulate_media(media="print"); sh("07_print"); pg.emulate_media(media="screen")
            pg.goto(B + "dieu-chinh.html?r=nam&code=M400", wait_until="domcontentloaded"); pg.wait_for_selector("#dlg[open] canvas"); ok("deep link", "M400" in pg.inner_text("#dlg-t")); pg.keyboard.press("Escape")
        pg.goto(B + "index.html", wait_until="domcontentloaded"); pg.wait_for_selector("#dcw:not([hidden]) .c"); pg.wait_for_timeout(300)
        ok(f"{mode} home card", pg.locator("#dcw .c").count() == 4); ok(f"{mode} nav badge", pg.locator(".hn-badge:not([hidden])").count() == 1)
        pg.locator("#dcw").scroll_into_view_if_needed(); sh("08_home_card", False)
        ctx.close()
    b.close()
for e in errs: print("ERR", e)
ok("no console/page errors", not errs, len(errs))
print(f"{sum(1 for _, c in R if c)}/{len(R)} passed"); sys.exit(0 if all(c for _, c in R) else 1)
